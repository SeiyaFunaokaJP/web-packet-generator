//! Golden-file assertions against `tests/golden/<name>.hex` at the workspace root.

use std::path::PathBuf;

use crate::hex::{hex, to_hex};
use crate::pcap::write_pcap;

/// Directory holding the golden files (`<workspace>/tests/golden`).
#[must_use]
pub fn golden_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/golden")
}

fn updating() -> bool {
    std::env::var("WPG_UPDATE_GOLDEN").is_ok_and(|v| v == "1")
}

/// Compares `bytes` with `tests/golden/<name>.hex` (one hex string, `#` comments
/// allowed). With `WPG_UPDATE_GOLDEN=1` the `.hex` file and a matching `.pcap` are
/// (re)written instead.
///
/// # Panics
/// On mismatch or a missing file (with a hint on how to regenerate).
pub fn assert_golden(name: &str, bytes: &[u8]) {
    let dir = golden_dir();
    let hex_path = dir.join(format!("{name}.hex"));
    if updating() {
        std::fs::create_dir_all(&dir).expect("create golden dir");
        let body = format!(
            "# {name}: generated by `WPG_UPDATE_GOLDEN=1 cargo test -p wpg-golden-tests`\n{}\n",
            to_hex(bytes)
        );
        std::fs::write(&hex_path, body).expect("write golden hex");
        write_pcap(dir.join(format!("{name}.pcap")), &[bytes.to_vec()]).expect("write golden pcap");
        return;
    }
    let text = std::fs::read_to_string(&hex_path).unwrap_or_else(|e| {
        panic!(
            "cannot read {}: {e} (run with WPG_UPDATE_GOLDEN=1 to create it)",
            hex_path.display()
        )
    });
    let expected = hex(&text);
    assert!(
        expected == bytes,
        "golden mismatch for {name}\n  expected: {}\n  actual:   {}\n(run with WPG_UPDATE_GOLDEN=1 to update)",
        to_hex(&expected),
        to_hex(bytes)
    );
}
