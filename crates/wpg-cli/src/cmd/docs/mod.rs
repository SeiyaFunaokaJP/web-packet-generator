//! `wpg docs gen`: generates the reference chapters of the mdBook documentation
//! from the code (TODO M11 "プロトコルリファレンス自動生成", "API / CLI / 設定 /
//! テンプレスキーマ リファレンス").
//!
//! Every page is produced in each [`Locale`] (`docs/<lang>/src/`), with the fixed
//! texts and the field descriptions taken from the Fluent files:
//!
//! * [`protocols`]: `reference/protocols.md` (index) and one page per catalog entry
//!   under `reference/protocols/`, the matching `SUMMARY.md` entries, and a block
//!   of links at the end of each hand-written page of `protocols/`;
//! * [`cli`]: `reference/cli.md` from the clap definition (`--help` of every command);
//! * [`api`]: `reference/api.md` and `docs/schema/openapi.json` from the utoipa
//!   document;
//! * [`config`]: `reference/config.md` from the JSON Schema of `wpg.toml`;
//! * [`schema`]: the key reference at the end of `reference/template-schema.md`
//!   from the template JSON Schema.
//!
//! Whole files start with a "generated" comment; generated parts of hand-written
//! files sit between `<!-- wpg-docs-gen:begin NAME -->` and
//! `<!-- wpg-docs-gen:end NAME -->`. Nothing here lists protocols or commands by
//! hand, so new ones are picked up by re-running `just docs-gen`; the test at the
//! bottom fails while the committed files are stale.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use wpg_i18n::{t, Locale};

use crate::cmd::cli_locale;
use crate::cmd::send::tr;
use crate::{DocsAction, DocsArgs};

pub(crate) mod api;
pub(crate) mod cli;
pub(crate) mod config;
pub(crate) mod md;
pub(crate) mod protocols;
pub(crate) mod schema;

/// First line of every wholly generated Markdown file.
pub(crate) const GENERATED: &str =
    "<!-- Generated by `wpg docs gen` (`just docs-gen`) from the code. Do not edit. -->";

/// One generated file, or one generated region of a hand-written file.
#[derive(Debug)]
pub(crate) struct Output {
    /// Path relative to the repository root, `/`-separated.
    pub(crate) path: String,
    /// What goes there.
    pub(crate) content: Content,
}

/// See [`Output`].
#[derive(Debug)]
pub(crate) enum Content {
    /// The whole file.
    Whole(String),
    /// The text between the `NAME` markers; when the file has no such markers it is
    /// appended (`append`) or an error is reported.
    Region {
        /// Marker name.
        name: &'static str,
        /// Text between the markers (without them).
        body: String,
        /// Append the region when the markers are missing.
        append: bool,
    },
}

impl Output {
    pub(crate) fn whole(path: impl Into<String>, text: String) -> Self {
        Self {
            path: path.into(),
            content: Content::Whole(text),
        }
    }

    pub(crate) fn region(
        path: impl Into<String>,
        name: &'static str,
        body: String,
        append: bool,
    ) -> Self {
        Self {
            path: path.into(),
            content: Content::Region { name, body, append },
        }
    }
}

/// `docs/<lang>/src/<rel>`.
pub(crate) fn src_path(locale: Locale, rel: &str) -> String {
    format!("docs/{}/src/{rel}", locale.as_str())
}

/// Directories whose `.md` files all come from the generator; others there are
/// stale (a protocol was removed or renamed).
fn owned_dirs() -> Vec<String> {
    Locale::ALL
        .iter()
        .map(|&l| src_path(l, protocols::PAGE_DIR))
        .collect()
}

/// Reads a text file with `\n` line ends (a Windows checkout may have `\r\n`).
pub(crate) fn read_text(path: &Path) -> std::io::Result<String> {
    std::fs::read_to_string(path).map(|s| s.replace("\r\n", "\n"))
}

/// Everything the generator produces for the repository at `root`.
///
/// # Errors
/// A source file (template, hand-written page) cannot be read.
pub(crate) fn generate(root: &Path) -> Result<Vec<Output>, String> {
    let mut out = Vec::new();
    for locale in Locale::ALL {
        protocols::outputs(root, locale, &mut out)?;
        out.push(cli::output(locale));
        out.push(api::output(locale));
        out.push(config::output(locale));
        out.push(schema::output(locale));
    }
    out.push(api::openapi_json());
    Ok(out)
}

/// Files to write and files to delete so that the docs match the code.
#[derive(Debug, Default)]
pub(crate) struct Plan {
    /// Path (relative to the root) → new content, only where it differs.
    pub(crate) writes: BTreeMap<String, String>,
    /// Stale generated files (relative to the root).
    pub(crate) removes: Vec<String>,
}

const BEGIN: &str = "<!-- wpg-docs-gen:begin ";
const END: &str = "<!-- wpg-docs-gen:end ";

/// Puts `body` between the `name` markers of `text`.
fn splice(text: &str, name: &str, body: &str, append: bool) -> Option<String> {
    let begin = format!("{BEGIN}{name} -->");
    let end = format!("{END}{name} -->");
    let block = format!("{begin}\n{body}{end}");
    if let (Some(b), Some(e)) = (text.find(&begin), text.find(&end)) {
        if b < e {
            return Some(format!("{}{block}{}", &text[..b], &text[e + end.len()..]));
        }
    }
    if !append {
        return None;
    }
    let mut s = text.trim_end().to_owned();
    s.push_str("\n\n");
    s.push_str(&block);
    s.push('\n');
    Some(s)
}

/// Text of `text` with every generated region of name `name` removed (used to
/// read hand-written pages without what the generator put there).
pub(crate) fn without_region(text: &str, name: &str) -> String {
    let begin = format!("{BEGIN}{name} -->");
    let end = format!("{END}{name} -->");
    match (text.find(&begin), text.find(&end)) {
        (Some(b), Some(e)) if b < e => format!("{}{}", &text[..b], &text[e + end.len()..]),
        _ => text.to_owned(),
    }
}

/// Compares the generated docs with the files under `root`.
///
/// # Errors
/// Reading a source fails, or a hand-written file lacks its markers.
pub(crate) fn plan(root: &Path) -> Result<Plan, String> {
    let outputs = generate(root)?;
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let mut current: BTreeMap<String, Option<String>> = BTreeMap::new();
    for o in outputs {
        let disk = current
            .entry(o.path.clone())
            .or_insert_with(|| read_text(&root.join(&o.path)).ok())
            .clone();
        let base = files.get(&o.path).cloned().or(disk);
        let new = match o.content {
            Content::Whole(text) => text,
            Content::Region { name, body, append } => {
                let base = base.ok_or_else(|| format!("{}: missing file", o.path))?;
                splice(&base, name, &body, append)
                    .ok_or_else(|| format!("{}: no `{BEGIN}{name} -->` marker", o.path))?
            }
        };
        files.insert(o.path, new);
    }
    let mut plan = Plan::default();
    for (path, text) in files {
        if current.get(&path).cloned().flatten().as_deref() != Some(text.as_str()) {
            plan.writes.insert(path, text);
        }
    }
    for dir in owned_dirs() {
        let Ok(rd) = std::fs::read_dir(root.join(&dir)) else {
            continue;
        };
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            let rel = format!("{dir}/{name}");
            if name.ends_with(".md") && !current.contains_key(&rel) {
                plan.removes.push(rel);
            }
        }
    }
    plan.removes.sort();
    Ok(plan)
}

/// Runs `wpg docs`.
pub(crate) fn run(args: &DocsArgs) -> ExitCode {
    let locale = cli_locale();
    match &args.action {
        DocsAction::Gen { root, check } => gen(root, *check, locale),
    }
}

fn gen(root: &Path, check: bool, locale: Locale) -> ExitCode {
    if !root.join("docs/en/src/SUMMARY.md").is_file() {
        eprintln!(
            "{}",
            tr(
                locale,
                "docs-gen-no-root",
                &[("path", root.display().to_string())]
            )
        );
        return ExitCode::FAILURE;
    }
    let plan = match plan(root) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("{}", tr(locale, "docs-gen-error", &[("error", e)]));
            return ExitCode::FAILURE;
        }
    };
    if check {
        for p in plan.writes.keys() {
            println!("{}", tr(locale, "docs-gen-stale", &[("path", p.clone())]));
        }
        for p in &plan.removes {
            println!("{}", tr(locale, "docs-gen-extra", &[("path", p.clone())]));
        }
        if plan.writes.is_empty() && plan.removes.is_empty() {
            println!("{}", t(locale, "docs-gen-up-to-date"));
            return ExitCode::SUCCESS;
        }
        println!("{}", t(locale, "docs-gen-run-hint"));
        return ExitCode::FAILURE;
    }
    for (path, text) in &plan.writes {
        let full: PathBuf = root.join(path);
        let res = full
            .parent()
            .map_or(Ok(()), std::fs::create_dir_all)
            .and_then(|()| std::fs::write(&full, text));
        if let Err(e) = res {
            eprintln!(
                "{}",
                tr(
                    locale,
                    "docs-gen-error",
                    &[("error", format!("{path}: {e}"))]
                )
            );
            return ExitCode::FAILURE;
        }
    }
    for path in &plan.removes {
        if let Err(e) = std::fs::remove_file(root.join(path)) {
            eprintln!(
                "{}",
                tr(
                    locale,
                    "docs-gen-error",
                    &[("error", format!("{path}: {e}"))]
                )
            );
            return ExitCode::FAILURE;
        }
    }
    println!(
        "{}",
        tr(
            locale,
            "docs-gen-done",
            &[
                ("written", plan.writes.len().to_string()),
                ("removed", plan.removes.len().to_string()),
            ],
        )
    );
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    /// The committed reference pages match the code (CI fails on stale docs).
    #[test]
    fn generated_docs_are_up_to_date() {
        let plan = plan(&repo_root()).unwrap();
        let stale: Vec<&String> = plan.writes.keys().chain(&plan.removes).collect();
        assert!(
            stale.is_empty(),
            "generated docs are stale, run `just docs-gen` (cargo run -p wpg-cli -- docs gen) \
             and commit the result: {stale:?}"
        );
    }

    #[test]
    fn splice_replaces_or_appends() {
        let text = "a\n<!-- wpg-docs-gen:begin x -->\nold\n<!-- wpg-docs-gen:end x -->\nb\n";
        assert_eq!(
            splice(text, "x", "new\n", false).unwrap(),
            "a\n<!-- wpg-docs-gen:begin x -->\nnew\n<!-- wpg-docs-gen:end x -->\nb\n"
        );
        assert_eq!(splice("a\n", "y", "n\n", false), None);
        assert_eq!(
            splice("a\n", "y", "n\n", true).unwrap(),
            "a\n\n<!-- wpg-docs-gen:begin y -->\nn\n<!-- wpg-docs-gen:end y -->\n"
        );
        assert_eq!(without_region(text, "x"), "a\n\nb\n");
    }

    /// Every text the generator looks up exists in every locale (no key fallbacks
    /// in the committed pages).
    #[test]
    fn generator_texts_are_translated() {
        md::take_missing();
        generate(&repo_root()).unwrap();
        let missing = md::take_missing();
        assert!(missing.is_empty(), "missing Fluent messages: {missing:?}");
    }
}
